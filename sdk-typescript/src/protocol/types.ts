  // Authentication & Authorization (0x2000 - 0x20FF)
  AUTH_REQUIRED = 0x2001,
  AUTH_INVALID_CREDENTIALS = 0x2002,
  AUTH_TOKEN_EXPIRED = 0x2003,
  AUTH_TOKEN_INVALID = 0x2004,
  AUTH_FORBIDDEN = 0x2005,
  AUTH_DEVICE_MISMATCH = 0x2006,
  AUTH_SESSION_TERMINATED = 0x2007,

